const CURRENCY_DECIMALS = { JPY:0, KRW:0, VND:0, CLP:0, XOF:0, XAF:0, UGX:0, RWF:0, ISK:0, PYG:0, KMF:0, GNF:0, BIF:0, DJF:0, VUV:0, KWD:3, BHD:3, OMR:3, JOD:3, TND:3, IQD:3, LYD:3 };

const regionNames = new Intl.DisplayNames(["en"], { type: "region" });
const currencyNames = new Intl.DisplayNames(["en"], { type: "currency" });
const symbolOf = (code) =>
  new Intl.NumberFormat("en", { style: "currency", currency: code, currencyDisplay: "narrowSymbol" })
    .formatToParts(0).find((p) => p.type === "currency")?.value ?? code;
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const currencies = [...new Set(Object.values(COUNTRY_CURRENCY))].sort();
const lines = ["-- Generated by scripts/generate-reference-seed.mjs. Safe to re-run.", ""];
lines.push("insert into public.currencies (code, name, symbol, decimals) values");
lines.push(currencies.map((c) => `  (${q(c)}, ${q(currencyNames.of(c))}, ${q(symbolOf(c))}, ${CURRENCY_DECIMALS[c] ?? 2})`).join(",\n"));
lines.push("on conflict (code) do update set name = excluded.name, symbol = excluded.symbol, decimals = excluded.decimals;", "");

lines.push("insert into public.countries (code, name, default_currency) values");
lines.push(Object.entries(COUNTRY_CURRENCY).sort().map(([cc, cur]) => `  (${q(cc)}, ${q(regionNames.of(cc))}, ${q(cur)})`).join(",\n"));
lines.push("on conflict (code) do update set name = excluded.name, default_currency = excluded.default_currency;", "");

lines.push("insert into public.exchange_rates (currency_code, units_per_usd, source) values");
lines.push(Object.entries(RATES).filter(([c]) => currencies.includes(c)).sort().map(([c, r]) => `  (${q(c)}, ${r}, 'seed')`).join(",\n"));
lines.push("on conflict (currency_code) do nothing;", "");

mkdirSync("supabase", { recursive: true });
writeFileSync("supabase/seed.sql", lines.join("\n"));
console.log(`Wrote ${currencies.length} currencies, ${Object.keys(COUNTRY_CURRENCY).length} countries`);
